export const I18nContext = createContext<Locale>("zh");

export function translate(locale: Locale, key: MsgKey): string {
  return (locale === "zh" ? ZH : EN)[key];
}

export function useI18n(): { locale: Locale; t: (key: MsgKey) => string } {
  const locale = useContext(I18nContext);
  return { locale, t: (key: MsgKey) => translate(locale, key) };
}

